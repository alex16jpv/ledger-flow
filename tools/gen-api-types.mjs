import { mkdirSync, writeFileSync } from "node:fs";

import openapiTS, { astToString } from "openapi-typescript";
import prettier from "prettier";

const apiUrl = (process.env.API_URL ?? "http://localhost:3000").replace(/\/$/, "");

async function fetchSpec() {
  const response = await fetch(`${apiUrl}/api-docs.json`);
  if (!response.ok) throw new Error(`Cannot reach ${apiUrl}/api-docs.json (${response.status})`);
  return response.json();
}

const METHODS = ["get", "post", "put", "patch", "delete", "head", "options"];

const sortByKey = (object, compare) =>
  Object.fromEntries(Object.entries(object).sort(([a], [b]) => compare(a, b)));

const alphabetical = (a, b) => a.localeCompare(b, "en");
const byMethod = (a, b) => {
  const order = METHODS.indexOf(a) - METHODS.indexOf(b);
  return order === 0 ? alphabetical(a, b) : order;
};

// The backend lists its paths in registration order, which changes between processes: without this
// every regeneration rewrites all 2394 lines of types/api.d.ts and no reviewer can see the contract
// that actually moved.
function sortSpec(spec) {
  const paths = sortByKey(spec.paths ?? {}, alphabetical);
  return {
    ...spec,
    paths: Object.fromEntries(
      Object.entries(paths).map(([path, item]) => [path, sortByKey(item, byMethod)]),
    ),
    components: {
      ...spec.components,
      schemas: sortByKey(spec.components?.schemas ?? {}, alphabetical),
    },
  };
}

const schemaName = (schema) =>
  schema?.$ref?.replace("#/components/schemas/", "") ??
  (schema?.type === "array" ? `${schemaName(schema.items)}[]` : (schema?.type ?? "—"));

const jsonSchemaOf = (body) => body?.content?.["application/json"]?.schema;

function parameterType(schema) {
  if (!schema) return "—";
  if (schema.enum) return schema.enum.map((value) => `\`${value}\``).join(" | ");
  const bounds = [
    schema.minimum !== undefined || schema.maximum !== undefined
      ? `${schema.minimum ?? ""}–${schema.maximum ?? ""}`
      : "",
    schema.default !== undefined ? `default \`${schema.default}\`` : "",
  ].filter(Boolean);
  const base = schema.format ? `${schema.type} (${schema.format})` : (schema.type ?? "—");
  return bounds.length > 0 ? `${base}, ${bounds.join(", ")}` : base;
}

const oneLine = (text) => (text ?? "").replace(/\s*\n\s*/g, " ").trim();
const cell = (text) => oneLine(text).replace(/\|/g, "\\|");
const anchor = (group) => group.toLowerCase().replace(/[^a-z0-9]+/g, "-");

function operations(spec) {
  const list = [];
  for (const [path, item] of Object.entries(spec.paths ?? {})) {
    for (const [method, operation] of Object.entries(item)) {
      if (!METHODS.includes(method)) continue;
      list.push({
        path,
        method: method.toUpperCase(),
        group: operation.tags?.[0] ?? "Other",
        public: Array.isArray(operation.security) && operation.security.length === 0,
        operation,
      });
    }
  }
  return list;
}

function detail({ method, path, operation, ...entry }) {
  const lines = [`### \`${method} ${path}\``, ""];
  // Descriptions carry their own markdown — the sync ones are tables — so they go in as blocks.
  if (operation.description) lines.push(operation.description.trim(), "");
  if (entry.public) lines.push("No token required.", "");
  const params = operation.parameters ?? [];
  for (const where of ["path", "query", "header"]) {
    const group = params.filter((parameter) => parameter.in === where);
    if (group.length === 0) continue;
    lines.push(
      `**${where[0].toUpperCase()}${where.slice(1)}**`,
      "",
      "| Name | Type | Required | Description |",
      "| --- | --- | --- | --- |",
      ...group.map(
        (parameter) =>
          `| \`${parameter.name}\` | ${cell(parameterType(parameter.schema))} | ${parameter.required ? "yes" : "no"} | ${cell(parameter.description)} |`,
      ),
      "",
    );
  }
  const body = jsonSchemaOf(operation.requestBody);
  if (body)
    lines.push(
      `**Body** \`${schemaName(body)}\`${operation.requestBody.required ? " (required)" : ""}`,
      "",
    );
  lines.push(
    "**Responses**",
    "",
    "| Status | Schema | Description |",
    "| --- | --- | --- |",
    ...Object.entries(operation.responses ?? {}).map(([status, response]) => {
      const schema = jsonSchemaOf(response);
      return `| \`${status}\` | ${schema ? `\`${schemaName(schema)}\`` : "—"} | ${cell(response.description)} |`;
    }),
    "",
  );
  return lines.join("\n");
}

function endpointsMarkdown(spec) {
  const list = operations(spec);
  const groups = [...new Set(list.map((entry) => entry.group))].sort(alphabetical);
  const scheme = spec.components?.securitySchemes?.bearerAuth;
  const lines = [
    "<!-- Generated by tools/gen-api-types.mjs from the backend OpenAPI. Do not edit. -->",
    "",
    `# ${spec.info?.title ?? "API"} endpoints`,
    "",
    `Version ${spec.info?.version ?? "?"} · ${list.length} operations · ${Object.keys(spec.components?.schemas ?? {}).length} schemas.`,
    "",
    "Regenerate with `npm run gen:api-types` against a running backend. The client never calls these",
    "URLs directly: every request goes through the BFF under `/api/*` (`lib/api`), which adds the",
    `${scheme ? `\`${scheme.scheme}\` ${scheme.bearerFormat ?? ""} token`.trim() : "token"} from the session cookies.`,
    "",
    "| Group | Operations |",
    "| --- | --- |",
    ...groups.map(
      (group) =>
        `| [${group}](#${anchor(group)}) | ${list.filter((entry) => entry.group === group).length} |`,
    ),
    "",
  ];
  for (const group of groups) {
    const entries = list.filter((entry) => entry.group === group);
    lines.push(
      `## ${group}`,
      "",
      "| Endpoint | Auth | Summary |",
      "| --- | --- | --- |",
      ...entries.map(
        (entry) =>
          `| \`${entry.method} ${entry.path}\` | ${entry.public ? "public" : "bearer"} | ${cell(entry.operation.summary)} |`,
      ),
      "",
      ...entries.map(detail),
    );
  }
  return lines.join("\n");
}

const spec = sortSpec(await fetchSpec());
const ast = await openapiTS(spec, {
  exportType: true,
  rootTypes: true,
  rootTypesNoSchemaPrefix: true,
});
const header = "// Generated by tools/gen-api-types.mjs from the backend OpenAPI. Do not edit.\n\n";
mkdirSync("types", { recursive: true });
writeFileSync("types/api.d.ts", header + astToString(ast));
const markdown = endpointsMarkdown(spec);
writeFileSync(
  "endpoints.md",
  await prettier.format(markdown, {
    ...(await prettier.resolveConfig("endpoints.md")),
    parser: "markdown",
  }),
);
if (process.argv.includes("--dump"))
  writeFileSync("types/openapi.json", JSON.stringify(spec, null, 2));
console.log(
  `gen-api-types: ${Object.keys(spec.paths ?? {}).length} paths, ${Object.keys(spec.components?.schemas ?? {}).length} schemas → types/api.d.ts, endpoints.md`,
);
